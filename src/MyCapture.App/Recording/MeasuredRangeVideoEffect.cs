    internal MeasuredRangeVideoEffect() : this(null) { }
    internal MeasuredRangeVideoEffect(MeasuredRangeCurve? mapping)
    {
        Mapping = mapping;
        var shader = new PixelShader();
        shader.SetStreamSource(new MemoryStream(Bytecode, writable: false));
        shader.Freeze();
        PixelShader = shader;
        if (mapping is not null)
        {
            var bitmap = BitmapSource.Create(256, 1, 96, 96, PixelFormats.Bgra32, null, mapping.Texture(), 256 * 4);
            bitmap.Freeze();
            var brush = new ImageBrush(bitmap) { Stretch = Stretch.Fill, TileMode = TileMode.None };
            RenderOptions.SetBitmapScalingMode(brush, BitmapScalingMode.NearestNeighbor);
            brush.Freeze();
            Lookup = brush;
        }
        UpdateShaderValue(InputProperty);
        UpdateShaderValue(LookupProperty);
    }

    internal MeasuredRangeCurve? Mapping { get; }
    internal static ReadOnlySpan<byte> BytecodeForTest => Bytecode;
    internal Brush Input { get => (Brush)GetValue(InputProperty); set => SetValue(InputProperty, value); }
    internal Brush Lookup { get => (Brush)GetValue(LookupProperty); set => SetValue(LookupProperty, value); }
    protected override Freezable CreateInstanceCore() => new MeasuredRangeVideoEffect();
