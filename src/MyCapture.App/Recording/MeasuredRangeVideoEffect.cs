    internal const string Source = """
        sampler2D Input : register(s0);
        sampler2D Lookup : register(s1);

        float4 main(float2 uv : TEXCOORD) : COLOR
        {
            float4 color = tex2D(Input, uv);
            // Work in byte units so half-entry boundaries are exactly representable.
            float denominator = max(floor(color.a * 255.0 + 0.5), 1.0);
            float3 numerator = floor(color.rgb * 255.0 + 0.5) * 255.0;
            float3 entry = floor(numerator / denominator + 0.5);
            // WPF software ps_2_0 uses an approximate reciprocal. Check the estimate
            // against exact half-entry products before addressing a steep LUT at alpha < 1.
            entry += step((entry + 0.5) * denominator, numerator);
            entry -= 1.0 - step((entry - 0.5) * denominator, numerator);
            entry = clamp(entry, 0.0, 255.0);
            float3 address = (entry * 4.0 + 1.5) / 1024.0;
            float3 corrected;
            corrected.r = tex2D(Lookup, float2(address.r, 128.5 / 256.0)).r;
            corrected.g = tex2D(Lookup, float2(address.g, 128.5 / 256.0)).g;
            corrected.b = tex2D(Lookup, float2(address.b, 128.5 / 256.0)).b;
            return float4(corrected * color.a, color.a);
        }
        """;

