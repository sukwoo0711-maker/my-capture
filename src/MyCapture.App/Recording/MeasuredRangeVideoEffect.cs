    internal MeasuredRangeVideoEffect() : this(null) { }
    internal MeasuredRangeVideoEffect(MeasuredRangeCurve? mapping)
    {
        Mapping = mapping;
        var shader = new PixelShader();
        shader.SetStreamSource(new MemoryStream(Bytecode, writable: false));
        shader.Freeze();
        PixelShader = shader;
        if (mapping is not null)
        {
            var bitmap = BitmapSource.Create(MeasuredRangeCurve.TextureWidth, MeasuredRangeCurve.TextureHeight,
                96, 96, PixelFormats.Bgra32, null, mapping.Texture(), MeasuredRangeCurve.TextureWidth * 4);
            bitmap.Freeze();
            // ImageBrush/VisualBrush shader inputs are rasterised at the effect's size,
            // losing LUT entries below 256px (and shifting texels at non-integral scales).
            // BitmapCacheBrush supplies its own cache texture to the sampler instead:
            // WPF ShaderEffect.cpp PrepareCacheBrushSamplerSw/Hw, rather than
            // PrepareTileBrushSamplerSw/Hw -> DrawIntoIntermediate.
            // Keep this detached visual at 1024x256 and its cache at scale 1. Each entry
            // occupies four columns and all rows: (round(value) * 4 + 1.5)/1024 addresses an
            // inner texel centre of that group. Rounding also stabilises alpha < 1. Point
            // and bilinear filtering both read the entry, far from the texture border.
            var visual = new DrawingVisual();
            RenderOptions.SetBitmapScalingMode(visual, BitmapScalingMode.NearestNeighbor);
            using (DrawingContext drawing = visual.RenderOpen())
                drawing.DrawImage(bitmap, new Rect(0, 0, MeasuredRangeCurve.TextureWidth, MeasuredRangeCurve.TextureHeight));
            Lookup = new BitmapCacheBrush(visual) { BitmapCache = new BitmapCache(1) };
        }
        UpdateShaderValue(InputProperty);
        UpdateShaderValue(LookupProperty);
    }

    internal MeasuredRangeCurve? Mapping { get; }
    internal static ReadOnlySpan<byte> BytecodeForTest => Bytecode;
    internal Brush Input { get => (Brush)GetValue(InputProperty); set => SetValue(InputProperty, value); }
    internal Brush Lookup { get => (Brush)GetValue(LookupProperty); set => SetValue(LookupProperty, value); }
    protected override Freezable CreateInstanceCore() => new MeasuredRangeVideoEffect();
}
