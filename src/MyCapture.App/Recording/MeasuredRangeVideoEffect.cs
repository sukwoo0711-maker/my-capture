        sampler2D Input : register(s0);
        sampler2D Lookup : register(s1);

        float4 main(float2 uv : TEXCOORD) : COLOR
        {
            float4 color = tex2D(Input, uv);
            // Unpremultiply before addressing the LUT; restore coverage after the lookup.
            float3 straight = saturate(color.rgb / max(color.a, 1.0 / 255.0));
            float3 address = (straight * 255.0 + 0.5) / 256.0;
            float3 corrected;
            corrected.r = tex2D(Lookup, float2(address.r, 0.5)).r;
            corrected.g = tex2D(Lookup, float2(address.g, 0.5)).g;
            corrected.b = tex2D(Lookup, float2(address.b, 0.5)).b;
            return float4(corrected * color.a, color.a);
