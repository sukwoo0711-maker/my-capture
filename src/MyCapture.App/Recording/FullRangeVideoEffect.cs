/// <summary>Reverses a presenter's erroneous studio expansion of full-range source RGB.</summary>
/// <remarks>
/// Premultiplied RGB is compressed by 219/255 and offset by alpha * 16/255.
/// Already clipped source values below 16 or above 235 are lost and display as 16/235.
/// The bytecode is compiled from <see cref="Source"/> with
/// <c>D3DCompile(..., "main", "ps_2_0", D3DCOMPILE_OPTIMIZATION_LEVEL3)</c>.
/// </remarks>
internal sealed class FullRangeVideoEffect : ShaderEffect
{
    internal const string Source = """
        sampler2D Input : register(s0);

        float4 main(float2 uv : TEXCOORD) : COLOR
        {
            float4 color = tex2D(Input, uv);
            // Premultiplied: offset scales with coverage, preserving transparent pixels.
            color.rgb = color.rgb * (219.0 / 255.0) + color.a * (16.0 / 255.0);
            return color;
        }
        """;

